import { useRef, useEffect, useCallback } from 'react';
import { cn } from '@/utils/cn';
import { Button } from '@/components/ui';
import { Download } from 'lucide-react';

export interface VerdictCardData {
  productName: string;
  verdict: 'GO' | 'NO-GO';
  revenue: number;
  profit: number;
  roas: number | null;
  breakEvenRoas: number | null;
  deliveryRate: number;
  currency: string;
}

interface VerdictCardProps {
  data: VerdictCardData;
  className?: string;
}

/** Format a number as currency for the card */
function fmtCurrency(amount: number, currency: string): string {
  return `${currency} ${amount.toLocaleString('en-PK', { maximumFractionDigits: 0 })}`;
}

/** Format multiplier value */
function fmtMultiplier(val: number | null): string {
  if (val === null || !isFinite(val)) return 'N/A';
  return `${val.toFixed(2)}x`;
}

/**
 * Renders a branded verdict card on an HTML canvas element.
 * The card can be downloaded as a PNG image.
 */
export default function VerdictCard({ data, className }: VerdictCardProps) {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  const drawCard = useCallback(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;

    const dpr = window.devicePixelRatio || 1;
    const width = 600;
    const height = 400;

    canvas.width = width * dpr;
    canvas.height = height * dpr;
    // Do NOT set canvas.style.width/height here — let CSS handle display size
    // so the canvas scales responsively within its container.

    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    ctx.scale(dpr, dpr);

    // Background — Deep Plum (#201034)
    ctx.fillStyle = '#201034';
    roundRect(ctx, 0, 0, width, height, 16);
    ctx.fill();

    // Gradient accent bar at top
    const gradient = ctx.createLinearGradient(0, 0, width, 0);
    gradient.addColorStop(0, '#DE85E2');
    gradient.addColorStop(0.5, '#DE8DDB');
    gradient.addColorStop(1, '#C9D0FC');
    ctx.fillStyle = gradient;
    ctx.fillRect(0, 0, width, 6);

    // Brand name
    ctx.fillStyle = '#FFFFFF';
    ctx.font = 'bold 22px system-ui, -apple-system, sans-serif';
    ctx.textAlign = 'left';
    ctx.fillText('LaunchLens AI', 32, 48);

    // Subtitle
    ctx.fillStyle = 'rgba(255,255,255,0.6)';
    ctx.font = '13px system-ui, -apple-system, sans-serif';
    ctx.fillText('Launch Verdict Card', 32, 68);

    // Product name
    ctx.fillStyle = '#FFFFFF';
    ctx.font = 'bold 18px system-ui, -apple-system, sans-serif';
    const productName = data.productName || 'Untitled Product';
    const truncatedName = productName.length > 40 ? productName.slice(0, 37) + '...' : productName;
    ctx.fillText(truncatedName, 32, 104);

    // Verdict badge
    const isGo = data.verdict === 'GO';
    const badgeColor = isGo ? '#9DD37D' : '#E88B9E';
    const badgeText = isGo ? 'GO \u2705' : 'NO-GO \u274C';
    const badgeWidth = ctx.measureText(badgeText).width + 32;

    ctx.fillStyle = badgeColor;
    roundRect(ctx, 32, 120, badgeWidth, 36, 18);
    ctx.fill();

    ctx.fillStyle = '#171717';
    ctx.font = 'bold 16px system-ui, -apple-system, sans-serif';
    ctx.fillText(badgeText, 48, 144);

    // Metrics grid
    const metricsY = 184;
    const colWidth = 260;
    const rowHeight = 44;

    const metrics = [
      { label: 'Revenue', value: fmtCurrency(data.revenue, data.currency) },
      { label: 'Profit', value: fmtCurrency(data.profit, data.currency) },
      { label: 'ROAS', value: fmtMultiplier(data.roas) },
      { label: 'Break-Even ROAS', value: fmtMultiplier(data.breakEvenRoas) },
      { label: 'Delivery Rate', value: `${data.deliveryRate}%` },
    ];

    metrics.forEach((metric, i) => {
      const col = i % 2;
      const row = Math.floor(i / 2);
      const x = 32 + col * colWidth;
      const y = metricsY + row * rowHeight;

      // Label
      ctx.fillStyle = 'rgba(255,255,255,0.55)';
      ctx.font = '12px system-ui, -apple-system, sans-serif';
      ctx.textAlign = 'left';
      ctx.fillText(metric.label, x, y);

      // Value
      ctx.fillStyle = '#FFFFFF';
      ctx.font = 'bold 16px system-ui, -apple-system, sans-serif';
      ctx.fillText(metric.value, x, y + 20);
    });

    // Divider line
    ctx.strokeStyle = 'rgba(255,255,255,0.12)';
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.moveTo(32, height - 52);
    ctx.lineTo(width - 32, height - 52);
    ctx.stroke();

    // Footer disclaimer
    ctx.fillStyle = 'rgba(255,255,255,0.4)';
    ctx.font = '11px system-ui, -apple-system, sans-serif';
    ctx.textAlign = 'center';
    ctx.fillText('Generated by LaunchLens AI \u2022 Figures are estimates, not guarantees', width / 2, height - 24);
  }, [data]);

  useEffect(() => {
    drawCard();
  }, [drawCard]);

  const handleDownload = () => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    try {
      const link = document.createElement('a');
      link.download = `verdict-${data.productName.replace(/[^a-zA-Z0-9]/g, '-').toLowerCase() || 'analysis'}.png`;
      link.href = canvas.toDataURL('image/png');
      link.click();
    } catch {
      // Canvas may be tainted in some environments
    }
  };

  return (
    <div className={cn('space-y-3', className)} data-icod-id="src_components_verdictcard_tsx_root">
      {/* Responsive wrapper: canvas renders at 600x400 internally, CSS scales it
          to fit the container width so nothing clips at narrow viewports (390px). */}
      <div className="w-full max-w-[600px] overflow-hidden" data-icod-id="src_components_verdictcard_tsx_canvas_wrap">
        <canvas
          ref={canvasRef}
          className="h-auto w-full rounded-xl shadow-lg"
          style={{ aspectRatio: '600/400' }}
          data-icod-id="src_components_verdictcard_tsx_canvas"
        />
      </div>
      <Button
        variant="outline"
        size="sm"
        onClick={handleDownload}
        className="gap-2"
        data-icod-id="src_components_verdictcard_tsx_download_btn"
      >
        <Download className="h-4 w-4" data-icod-id="src_components_verdictcard_tsx_download_icon" />
        Download Card
      </Button>
    </div>
  );
}

/** Helper to draw a rounded rectangle path */
function roundRect(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
): void {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.lineTo(x + w - r, y);
  ctx.quadraticCurveTo(x + w, y, x + w, y + r);
  ctx.lineTo(x + w, y + h - r);
  ctx.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  ctx.lineTo(x + r, y + h);
  ctx.quadraticCurveTo(x, y + h, x, y + h - r);
  ctx.lineTo(x, y + r);
  ctx.quadraticCurveTo(x, y, x + r, y);
  ctx.closePath();
}
